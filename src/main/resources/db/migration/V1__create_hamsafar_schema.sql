CREATE SCHEMA IF NOT EXISTS app;

REVOKE ALL ON SCHEMA app FROM PUBLIC;

CREATE TABLE app.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    phone VARCHAR(30),
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role
        CHECK (role IN ('PASSENGER', 'DRIVER', 'ADMIN'))
);

CREATE TABLE app.driver_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    driver_phone VARCHAR(30) NOT NULL,
    introduction TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_driver_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_driver_profiles_user
        FOREIGN KEY (user_id) REFERENCES app.users (id)
);

CREATE TABLE app.vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id BIGINT NOT NULL,
    vehicle_type VARCHAR(50) NOT NULL,
    manufacturer VARCHAR(50),
    model_name VARCHAR(100) NOT NULL,
    license_plate VARCHAR(30) NOT NULL,
    passenger_capacity SMALLINT NOT NULL,
    trunk_volume_liter INTEGER,
    max_luggage_count SMALLINT NOT NULL,
    large_luggage_capacity SMALLINT,
    vehicle_image_url VARCHAR(500),
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_vehicles_driver UNIQUE (driver_id),
    CONSTRAINT uk_vehicles_license_plate UNIQUE (license_plate),
    CONSTRAINT fk_vehicles_driver
        FOREIGN KEY (driver_id) REFERENCES app.driver_profiles (id),
    CONSTRAINT ck_vehicles_passenger_capacity
        CHECK (passenger_capacity > 0),
    CONSTRAINT ck_vehicles_trunk_volume
        CHECK (trunk_volume_liter IS NULL OR trunk_volume_liter >= 0),
    CONSTRAINT ck_vehicles_luggage_capacity
        CHECK (max_luggage_count >= 0),
    CONSTRAINT ck_vehicles_large_luggage_capacity
        CHECK (large_luggage_capacity IS NULL OR large_luggage_capacity >= 0)
);

CREATE TABLE app.ride_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id BIGINT NOT NULL,
    title VARCHAR(200),
    meeting_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    join_deadline_at TIMESTAMP WITHOUT TIME ZONE,
    meeting_address VARCHAR(500) NOT NULL,
    meeting_place_name VARCHAR(200),
    meeting_latitude NUMERIC(10, 7),
    meeting_longitude NUMERIC(10, 7),
    destination_address VARCHAR(500),
    destination_place_name VARCHAR(200),
    destination_latitude NUMERIC(10, 7),
    destination_longitude NUMERIC(10, 7),
    fare_type VARCHAR(20) NOT NULL,
    fare_amount BIGINT NOT NULL,
    max_passenger_count SMALLINT NOT NULL,
    max_luggage_count SMALLINT NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_ride_schedules_driver
        FOREIGN KEY (driver_id) REFERENCES app.driver_profiles (id),
    CONSTRAINT ck_ride_schedules_deadline
        CHECK (join_deadline_at IS NULL OR join_deadline_at <= meeting_at),
    CONSTRAINT ck_ride_schedules_meeting_latitude
        CHECK (meeting_latitude IS NULL OR meeting_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ride_schedules_meeting_longitude
        CHECK (meeting_longitude IS NULL OR meeting_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ride_schedules_destination_latitude
        CHECK (destination_latitude IS NULL OR destination_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ride_schedules_destination_longitude
        CHECK (destination_longitude IS NULL OR destination_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ride_schedules_fare_type
        CHECK (fare_type IN ('PER_PERSON', 'FIXED_TOTAL')),
    CONSTRAINT ck_ride_schedules_fare_amount
        CHECK (fare_amount >= 0),
    CONSTRAINT ck_ride_schedules_passenger_count
        CHECK (max_passenger_count > 0),
    CONSTRAINT ck_ride_schedules_luggage_count
        CHECK (max_luggage_count >= 0),
    CONSTRAINT ck_ride_schedules_status
        CHECK (status IN ('OPEN', 'CLOSED', 'DEPARTED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE app.ride_joins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    passenger_count SMALLINT NOT NULL,
    luggage_count SMALLINT NOT NULL,
    large_luggage_count SMALLINT,
    special_luggage_note VARCHAR(500),
    unit_fare_snapshot BIGINT NOT NULL,
    total_fare BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    cancelled_at TIMESTAMP WITHOUT TIME ZONE,
    joined_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_ride_joins_schedule
        FOREIGN KEY (schedule_id) REFERENCES app.ride_schedules (id),
    CONSTRAINT fk_ride_joins_user
        FOREIGN KEY (user_id) REFERENCES app.users (id),
    CONSTRAINT ck_ride_joins_passenger_count
        CHECK (passenger_count > 0),
    CONSTRAINT ck_ride_joins_luggage_count
        CHECK (luggage_count >= 0),
    CONSTRAINT ck_ride_joins_large_luggage_count
        CHECK (large_luggage_count IS NULL OR large_luggage_count >= 0),
    CONSTRAINT ck_ride_joins_unit_fare
        CHECK (unit_fare_snapshot >= 0),
    CONSTRAINT ck_ride_joins_total_fare
        CHECK (total_fare >= 0),
    CONSTRAINT ck_ride_joins_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'COMPLETED', 'NO_SHOW'))
);

CREATE INDEX idx_users_deleted_at
    ON app.users (deleted_at);

CREATE INDEX idx_ride_schedules_meeting_at
    ON app.ride_schedules (meeting_at);

CREATE INDEX idx_ride_schedules_driver_meeting
    ON app.ride_schedules (driver_id, meeting_at);

CREATE INDEX idx_ride_joins_schedule_status
    ON app.ride_joins (schedule_id, status);

CREATE INDEX idx_ride_joins_user_joined
    ON app.ride_joins (user_id, joined_at DESC);

-- The application tables are deliberately isolated from Supabase's default
-- public Data API schema. RLS remains enabled as defense in depth if this
-- schema is ever exposed accidentally. No anon/authenticated policies exist.
ALTER TABLE app.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.driver_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.ride_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.ride_joins ENABLE ROW LEVEL SECURITY;
